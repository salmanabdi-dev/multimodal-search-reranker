"""Build reports/VERIFICATION.md from the artefacts a verification run leaves behind.

Every number in the generated file is read from a report the run wrote (pytest JUnit
XML, eval/bench/optimize/smoke JSON). Nothing is typed in by hand, so the summary can
always be traced back to, and regenerated from, its sources.
"""

from __future__ import annotations

import json
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any


def latest(reports: Path, prefix: str) -> tuple[Path, dict] | None:
    """Most recent `<prefix>_<UTC stamp>.json` (stamps sort lexicographically)."""
    files = sorted(reports.glob(f"{prefix}_2*.json"))
    if not files:
        return None
    return files[-1], json.loads(files[-1].read_text())


@dataclass
class JUnit:
    tests: int = 0
    failures: int = 0
    errors: int = 0
    skipped: int = 0
    seconds: float = 0.0
    failed: list[str] = field(default_factory=list)

    @property
    def passed(self) -> int:
        return self.tests - self.failures - self.errors - self.skipped

    @property
    def ok(self) -> bool:
        return self.tests > 0 and self.failures == 0 and self.errors == 0


def parse_junit(path: Path) -> JUnit:
    root = ET.parse(path).getroot()
    suites = [root] if root.tag == "testsuite" else list(root.iter("testsuite"))
    out = JUnit()
    for s in suites:
        out.tests += int(s.get("tests", 0))
        out.failures += int(s.get("failures", 0))
        out.errors += int(s.get("errors", 0))
        out.skipped += int(s.get("skipped", 0))
        out.seconds += float(s.get("time", 0.0))
        for case in s.iter("testcase"):
            if case.find("failure") is not None or case.find("error") is not None:
                out.failed.append(f"{case.get('classname')}::{case.get('name')}")
    return out


def _f(x: Any, fmt: str = ".4f") -> str:
    return "n/a" if x is None else format(x, fmt)


def _pct(x: Any) -> str:
    return "n/a" if x is None else f"{x:+.1%}"


def latency_rows(bench: dict) -> list[str]:
    rows = ["| Configuration | mean | p50 | p95 | p99 | p95 < target |", "|---|---|---|---|---|---|"]
    target = bench.get("target_p95_ms", 65.0)
    for label, r in bench.get("results", {}).items():
        t = r.get("total") or r.get("server_total") or r.get("client_total")
        verdict = "" if label.endswith("vector_only") else ("yes" if t["p95"] < target else "**no**")
        rows.append(f"| {label} | {t['mean']:.2f} | {t['p50']:.2f} | {t['p95']:.2f} | "
                    f"{t['p99']:.2f} | {verdict} |")
    return rows


def stage_rows(bench: dict, label: str) -> list[str]:
    r = bench.get("results", {}).get(label, {})
    stages = r.get("stages")
    if not stages:
        return []
    rows = [f"Per-stage breakdown, `{label}` (ms):", "",
            "| Stage | mean | p50 | p95 | share of mean |", "|---|---|---|---|---|"]
    share = r.get("stage_mean_share", {})
    for name, st in stages.items():
        rows.append(f"| {name} | {st['mean']:.2f} | {st['p50']:.2f} | {st['p95']:.2f} | "
                    f"{share.get(name, 0):.0%} |")
    return rows


def precision_rows(res: dict, a: str, b: str) -> list[str]:
    rows = [f"| Metric | {a} | {b} | Relative change |", "|---|---|---|---|"]
    for m in ("p@5", "p@5_strict", "ndcg@10", "mrr@10"):
        av, bv = res["a"].get(m), res["b"].get(m)
        rel = (bv - av) / av if av else None
        rows.append(f"| {m} | {_f(av)} | {_f(bv)} | {_pct(rel)} |")
    bs = res.get("bootstrap") or {}
    if bs:
        rows += ["", f"P@5 relative gain 95% CI: [{_pct(bs.get('rel_ci_low'))}, "
                     f"{_pct(bs.get('rel_ci_high'))}], p(B ≤ A) = {_f(bs.get('p_value_b_not_better'))}; "
                     f"{res['queries']} held-out queries; candidate-pool Recall@{res['n']} = "
                     f"{_f(res.get('pool_recall'))}."]
    return rows


def build_markdown(reports: Path, target_gain: float = 0.28) -> str:
    out: list[str] = ["# Verification report", "",
                      "Generated by `mmsearch report` from the files in `reports/`. "
                      "Every number below is read from those files.", ""]

    bench_final = latest(reports, "bench_inprocess_final") or latest(reports, "bench_inprocess")
    env = (bench_final[1].get("environment") if bench_final else None) or {}
    if env:
        out += ["## Environment", "",
                f"- CPU: {env.get('cpu')} ({env.get('logical_cpus')} logical CPUs visible), "
                f"{env.get('machine')}",
                f"- Python {env.get('python')}, torch {env.get('torch')}, "
                f"transformers {env.get('transformers')}, torch threads "
                f"{env.get('torch_threads')}, CUDA: {env.get('cuda') or 'none'}",
                f"- pgvector {bench_final[1].get('index', {}).get('pgvector_version')}", ""]

    out += ["## Tests", "", "| Suite | Passed | Failed | Errors | Skipped | Time |",
            "|---|---|---|---|---|---|"]
    failed_names: list[str] = []
    for name, file in (("unit", "junit_unit.xml"), ("integration", "junit_integration.xml")):
        p = reports / file
        if p.exists():
            j = parse_junit(p)
            out.append(f"| {name} | {j.passed} | {j.failures} | {j.errors} | {j.skipped} | "
                       f"{j.seconds:.0f} s |")
            failed_names += j.failed
        else:
            out.append(f"| {name} | not run | | | | |")
    if failed_names:
        out += ["", "Failing tests:", ""] + [f"- `{n}`" for n in failed_names]
    out.append("")

    smoke = latest(reports, "smoke")
    if smoke:
        checks = smoke[1]["checks"]
        passed = sum(c["ok"] for c in checks)
        out += [f"## End-to-end checks against the running API ({passed}/{len(checks)} passed)",
                "", "| Check | Result | Detail |", "|---|---|---|"]
        out += [f"| {c['name']} | {'pass' if c['ok'] else '**FAIL**'} | {c['detail']} |"
                for c in checks]
        out.append("")

    ev = latest(reports, "eval_final") or latest(reports, "eval")
    if ev and "test" in ev[1]:
        t = ev[1]["test"]
        met = "met" if t["rel_gain_p5"] >= target_gain else "**not met**"
        out += ["## Text retrieval quality (BEIR NFCorpus, held-out test split)", "",
                f"System A is vector retrieval only. System B adds cross-encoder reranking of "
                f"the top {t['n']} candidates. Configuration chosen on the dev split.", ""]
        out += precision_rows(t, "A vector", "B reranked")
        out += ["", f"**Top-5 precision improvement: {_pct(t['rel_gain_p5'])}** "
                    f"(target +{target_gain:.0%}: {met}). Source: `{ev[0].name}`.", ""]

    im = latest(reports, "eval_images")
    if im and "test" in im[1]:
        t = im[1]["test"]
        w = t.get("extra", {}).get("caption_weight")
        out += ["## Image retrieval quality (synthetic shapes, held-out test split)", "",
                f"System A is CLIP text-to-image retrieval. System B adds caption fusion "
                f"(weight {w}). Captions are deliberately partial.", ""]
        out += precision_rows(t, "A CLIP", "B fusion")
        cal = im[1].get("calibration")
        if cal:
            out += ["", f"CLIP calibration fit on dev: a = {cal['fitted']['a']:.3f}, "
                        f"b = {cal['fitted']['b']:.3f}; test log loss "
                        f"{cal['test_log_loss_current']:.4f} → {cal['test_log_loss_fitted']:.4f}."]
        out += ["", f"Source: `{im[0].name}`.", ""]

    ann = latest(reports, "ann_recall")
    if ann:
        out += ["## HNSW recall vs exact search (text index)", "",
                "| ef_search | Recall@" + str(ann[1]["k"]) + " | mean ms |", "|---|---|---|"]
        out += [f"| {r['ef_search']} | {r['recall']:.4f} | {r['mean_ms']:.3f} |"
                for r in ann[1]["rows"]]
        out.append("")

    base = latest(reports, "bench_inprocess_baseline")
    if base:
        out += ["## Latency before optimisation (in-process, ms)", ""] + latency_rows(base[1])
        out += [""] + stage_rows(base[1], "text+image") + ["", f"Source: `{base[0].name}`.", ""]

    opt = latest(reports, "optimize")
    if opt:
        o = opt[1]
        out += ["## Optimisation", "", "Thread sweep (p95 ms): " + ", ".join(
            f"{r['threads']} → {r['p95']:.1f}" for r in o["threads"]) +
            f"; selected {o['best_threads']}.", "",
            "| N | max_length | int8 | dev P@5 | text p95 | unified p95 |", "|---|---|---|---|---|---|"]
        out += [f"| {p['n']} | {p['max_length']} | {'yes' if p['quantize'] else 'no'} | "
                f"{p['dev_p5']:.4f} | {p['text_p95']:.2f} | {_f(p['unified_p95'], '.2f')} |"
                for p in o["grid"]]
        sel = o.get("selection") or {}
        if sel.get("point"):
            p = sel["point"]
            out += ["", f"Selected ({sel['reason']}): N={p['n']}, max_length={p['max_length']}, "
                        f"int8={'yes' if p['quantize'] else 'no'}. Applied settings: "
                        + ", ".join(f"`{e}`" for e in o.get("env", [])) + "."]
        out.append("")

    if bench_final:
        out += ["## Final latency (in-process, optimised settings, ms)", ""]
        out += latency_rows(bench_final[1]) + [""] + stage_rows(bench_final[1], "text+image")
        out += ["", f"Source: `{bench_final[0].name}`.", ""]
    http = latest(reports, "bench_http_final") or latest(reports, "bench_http")
    if http:
        out += ["## Final latency over HTTP (server time from Server-Timing, ms)", ""]
        out += latency_rows(http[1]) + ["", f"Source: `{http[0].name}`.", ""]
    return "\n".join(out) + "\n"
